/**
 * Largest share of the screen the pixel-art splash may cover.
 */
private const val SPLASH_MAX_SCREEN_FRACTION = 0.7f

@Composable
fun SplashScreen() {
	// Pixel art (branding/splash_logo.png, generated by branding/pixel_assets.py). It is drawn at the
	// largest whole-number scale that fits, without filtering, so every art pixel stays a crisp square.
	val logo = ImageBitmap.imageResource(R.drawable.splash_logo)
	val description = stringResource(R.string.splash_text)

	Box(
		modifier = Modifier
			.fillMaxSize()
			.background(colorResource(id = R.color.splash_background))
			.semantics { contentDescription = description }
			.drawBehind {
				val scale = maxOf(
					1,
					minOf(
						(size.width * SPLASH_MAX_SCREEN_FRACTION / logo.width).toInt(),
						(size.height * SPLASH_MAX_SCREEN_FRACTION / logo.height).toInt(),
					)
				)
				val width = logo.width * scale
				val height = logo.height * scale

				drawImage(
					image = logo,
					dstOffset = IntOffset(((size.width - width) / 2).toInt(), ((size.height - height) / 2).toInt()),
					dstSize = IntSize(width, height),
					filterQuality = FilterQuality.None,
				)
			},
	)
}

class SplashFragment : Fragment() {
	override fun onCreateView(
		inflater: LayoutInflater,
		container: ViewGroup?,
		savedInstanceState: Bundle?
	) = content {
		JellyfinTheme {
			SplashScreen()
		}
	}
}
